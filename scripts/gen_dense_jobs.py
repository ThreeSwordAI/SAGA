#!/usr/bin/env python3
"""
scripts/gen_dense_jobs.py
=========================
TASK-09: generate, per run of configs/dense_matrix.yaml, a SLURM job file
plus a submit script that chains N copies with --dependency=singleton,afterany
— every job executing the SAME `--resume auto` command (the trainers
fresh-start on the first job, resume on every successor, and a surplus job
exits in seconds via the completion fast-path).

    python scripts/gen_dense_jobs.py [--matrix configs/dense_matrix.yaml]

Emits, byte-for-byte deterministically:
    scripts/jobs/<run_id>.sbatch          6 runs
    scripts/submit_<run_id>.sh            6 chains
    scripts/jobs/dense_smoke_det.sbatch   50 iters + one capped eval
    scripts/jobs/dense_smoke_seg.sbatch   ... plus the on-device pytest

Every SLURM element is copied from committed, production-proven files:
the #SBATCH header from scripts/jobs/e2r_*.sbatch (How to Run.md §6:
partition a100, gpu:a100:4, 24 h wall, cpus-per-task 8, ntasks-per-node 4,
logs under $OUT_ROOT/logs), and the env + staging lines from the committed
detection/scripts/{env_alex,stage_coco}.sh and
segmentation/scripts/{env_alex,stage_ade20k}.sh (which is where the COCO and
ADE20K zip paths live — nothing here is invented).

Master ports: this file uses 29850..29855 for the six runs and 29860/29861
for the smokes. Every other committed launcher was enumerated before picking
that block, INCLUDING the ones whose port is computed from the array index
(`$((BASE + SLURM_ARRAY_TASK_ID))`), which a plain grep for a literal port
misses:
    29500 + 0..15  scripts/e1_variants{,_alex}.sh
    29600 + 0..8   classification/scripts/e2_train_alex.sh
    29698, 29699   scripts/saga_e2r{,_registers}_smoke.sh
    29700 + 0..2   classification/scripts/e2_sanity_alex.sh
    29700..29709   scripts/jobs/e2r_*.sbatch
    29750..29753   scripts/jobs/e2r_* (TASK-07 additions)
    29800 + 0..2   classification/scripts/e2_nomix_alex.sh   <-- the reason
                   this file no longer starts at 29800
    29900          detection/scripts/e3_sanity_alex.sh
    29910 + 0..2   detection/scripts/e3_train_alex.sh
    29920 + 0..2   segmentation/scripts/e4_{train,sanity}_alex.sh
tests/test_task09_dense.py re-derives that whole table from the repo and
asserts the dense ports are disjoint from it.
"""

