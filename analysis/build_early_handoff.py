def sec_address(L):
    A = L.append
    sa = rows("results/tables/sink_address.csv", enc="cp1252")

    def q(question, statistic, basis="canon", **kw):
        cand = [r for r in sa if r["question"] == question
                and r["statistic"] == statistic
                and r["map_basis"] == basis
                and all(r.get(k) == str(v) for k, v in kw.items())]
        if not cand:
            return None
        best = max(cand, key=lambda r: num(r["n"]) or 0)
        return num(best["value"])

    A("### 5.4 The sink address (TASK-07; "
      "`results/tables/sink_address.csv`, canon basis, exact spatial "
      "permutation nulls)\n")
    r1 = q("Q1b_geometry", "ring1_mean_freq", arch="vit_small",
           recipe_actual="mixup", variant="baseline", subject="s1")
    r0 = q("Q1b_geometry", "ring0_mean_freq", arch="vit_small",
           recipe_actual="mixup", variant="baseline", subject="s1")
    r1n = q("Q1b_geometry", "ring1_mean_freq", arch="vit_small",
            recipe_actual="nomix", variant="baseline", subject="s1")
    A(f"1. **Sinks have a spatial address, and it is a border RING** one "
      f"patch inside the edge for every mixup-trained member (S/mixup "
      f"baseline s1: ring-1 freq {pl(r1, 4)} vs ring-0 {pl(r0, 4)}), and "
      f"FLAT for true-nomix (ring-1 {pl(r1n, 4)}). The address is created "
      f"by the mixup recipe.")
