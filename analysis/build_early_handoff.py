import csv
import json
import re
import statistics
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "docs" / "early_handoff.md"
MISSING = "MISSING"


def sh(*args):
    try:
        return subprocess.run(args, capture_output=True, text=True,
                              cwd=str(REPO)).stdout.strip()
    except Exception:                                      # noqa: BLE001
        return ""


def rows(rel, enc="utf-8"):
    with open(REPO / rel, newline="", encoding=enc) as f:
        return list(csv.DictReader(f))


def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def pick(rs, **kw):
    return next((r for r in rs if all(r.get(k) == str(v)
                                      for k, v in kw.items())), None)


def val(rs, col, **kw):
    r = pick(rs, **kw)
    return num(r[col]) if r else None


def pl(v, nd=3):
    return MISSING if v is None else f"{v:.{nd}f}"


def sg(v, nd=3):
    return MISSING if v is None else f"{v:+.{nd}f}"


def note_verdict(rel, pattern):
    """Read a verdict string out of a committed generated note."""
    try:
        text = (REPO / rel).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return MISSING
    m = re.search(pattern, text)
    return m.group(1) if m else MISSING


def count_dirs(pattern, require=None):
    out = 0
    for p in sorted((REPO / "results").glob(pattern)):
        if not p.is_dir():
            continue
        if require and not (p / require).exists():
            continue
        out += 1
    return out


