def sec_legacy(L):
    A = L.append
    sr = rows("results/tables/sink_robustness.csv")
    lc = rows("results/tables/legacy_e2_corrected.csv")
    A("## 5. Results\n")
    A("### 5.0 Legacy re-derivation and metric robustness "
      "(TASK-02/02B/02C; `results/tables/legacy_e2_corrected.csv`, "
      "`sink_robustness.csv`)\n")
    A("All 12 usable legacy e2 runs were exactly re-derived (eval + "
      "diagnostics, sha-matched to the manifest, zero gaps) before "
      "anything else was built on them.")
    defs = ["sink_mad_k5", "sink_mu2s", "sink_mu3s", "sink_mu4s",
            "sink_mu5s", "sink_mu6s", "sink_fixed_thr"]

    def below(arch, rec):
        b = pick(sr, arch=arch, recipe=rec, variant="baseline")
        s = pick(sr, arch=arch, recipe=rec, variant="saga")
        return sum(1 for d in defs
                   if num(s[d]) is not None and num(b[d]) is not None
                   and num(s[d]) < num(b[d]))

    bb = pick(sr, arch="vit_base", recipe="nomix", variant="baseline")
    bs = pick(sr, arch="vit_base", recipe="nomix", variant="saga")
    above_defs = [d for d in defs
                  if num(bs[d]) is not None and num(bb[d]) is not None
                  and num(bs[d]) > num(bb[d])]
    A(f"- **Threshold robustness** (7 sink definitions × 4 dirname "
      f"cells): SAGA sits below baseline under {below('vit_small', 'mixup')} "
      f"of 7 definitions in ViT-S/mixup-dir and "
      f"{below('vit_small', 'nomix')} of 7 in ViT-S/nomix-dir; "
      f"ViT-B/nomix-dir shows the H1-predicted shape — SAGA below "
      f"baseline under {below('vit_base', 'nomix')} of 7 definitions but "
      f"ABOVE it under {', '.join(above_defs)}; the v1 per-arch tau "
      f"SATURATED on ViT-B/mixup-dir (baseline "
      f"{pl(val(sr, 'sink_fixed_thr', arch='vit_base', recipe='mixup', variant='baseline'), 4)}"
      f"/196) — which is what forced the per-cell threshold generations.")
    cls_up = sum(1 for arch in ("vit_small", "vit_base")
                 for rec in ("mixup", "nomix")
                 if (val(lc, "cls_norm_ratio_lastblock", arch=arch,
                         recipe=rec, variant="saga") or 0) >
                 (val(lc, "cls_norm_ratio_lastblock", arch=arch,
                      recipe=rec, variant="baseline") or 0))
    att_dn = sum(1 for arch in ("vit_small", "vit_base")
                 for rec in ("mixup", "nomix")
                 if (val(lc, "cls_attn_share_lastblock", arch=arch,
                         recipe=rec, variant="saga") or 0) <
                 (val(lc, "cls_attn_share_lastblock", arch=arch,
                      recipe=rec, variant="baseline") or 0))
    A(f"- **Relocation (F6)**: SAGA's final-block CLS-norm ratio ends "
      f"ABOVE baseline in {cls_up} of 4 legacy cells while its CLS "
      f"attention share ends BELOW baseline in {att_dn} of 4 — outlier "
      f"mass moves toward the ungated CLS token without CLS attention "
      f"growing. Norm-scale signatures per cell (threshold vs extremes): "
      f"ViT-B/nomix-dir shows BOTH H1 signatures (threshold shrank, "
      f"extremes grew); the other three cells match neither pattern "
      f"(`results/notes/gate1_addendum.md` §5).")
    A("- The ViT-B/mixup-dir trio was exposed as INCOMPLETE by the "
      "checkpoint forensics and declared VOID (section 3); the "
      "quarantine forced the seeded reruns below.\n")


def sec_classification(L):
    A = L.append
    p = rows("results/tables/e2_pooled.csv")
    A("### 5.1 ImageNet classification — the headline cells "
      "(`results/tables/e2_pooled.csv`, exact fp32 eval, top1_last)\n")
    A("| cell | baseline mean | SAGA mean | SAGA paired delta ± SE | "
      "sig 2×SE | registers paired delta |")
    A("|---|---|---|---|---|---|")
    for arch, rec, label in (("vit_small", "mixup", "ViT-S/16 mixup"),
                             ("vit_small", "nomix",
                              "ViT-S/16 true-nomix (n=2)"),
                             ("vit_base", "mixup", "ViT-B/16 mixup (n=2)")):
        base = val(p, "top1_last", arch=arch, recipe_actual=rec,
                   variant="baseline", kind="mean")
        sagam = val(p, "top1_last", arch=arch, recipe_actual=rec,
                    variant="saga", kind="mean")
