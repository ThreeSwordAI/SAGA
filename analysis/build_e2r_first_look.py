def main():
    parser = argparse.ArgumentParser(description="Generate e2r_first_look.md")
    parser.add_argument("--out", default="results/notes/e2r_first_look.md")
    args = parser.parse_args()

    rows = load_pooled()
    L = sec_header()
    L += sec_vitb_resolution()
    L += sec_consistency()
    L += sec_pooled(rows)
    L += sec_significance(rows)
    L += sec_vitb_sink(rows)
    L += sec_trainloss(rows)
    L += sec_gradphi()
    L += sec_gates()
    L += sec_open_items()

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L), encoding="utf-8", newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
