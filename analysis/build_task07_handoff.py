CELLS = [("vit_small", "mixup"), ("vit_small", "nomix"),
         ("vit_base", "mixup")]
VARIANTS = ["baseline", "saga", "registers"]
MISSING = "MISSING"


def load(path: Path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def git_sha() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                              capture_output=True, text=True,
                              check=True).stdout.strip()
    except Exception:
        return "unknown"


def repeat_counts(t: Table):
    """(cell, variant) -> number of repeats actually used."""
    out = {}
    for arch, rec in CELLS:
        for variant in VARIANTS:
            r = t.one(question="Q1_concentration", arch=arch,
                      recipe_actual=rec, map_basis="canon", variant=variant,
                      subject="MEAN", statistic="gini")
            out[(arch, rec, variant)] = int(r["n"]) if r else 0
    return out


def pooled_lookup(pooled, arch, rec, variant, kind, metric="top1_last"):
    """The single row of this kind, formatted, or None."""
    for r in pooled:
        if (r["arch"] == arch and r["recipe_actual"] == rec
                and r["variant"] == variant and r["kind"] == kind):
            v = r[metric]
            if v in ("", MISSING):
                return None
            try:
                if kind == "significant_2xSE":      # a 0/1 flag, not a value
                    return str(int(float(v)))
                return f"{float(v):+.3f}" if kind.endswith("delta_mean") \
                    else f"{float(v):.3f}"
            except ValueError:
                return v
    return None


def pooled_deltas(pooled, arch, rec, variant, metric="top1_last"):
    """[(provenance, formatted value)] for EVERY paired delta — the spread
    between them is the reason the mean is or is not significant, so all of
    them must be quoted, not just the first."""
    out = []
    for r in pooled:
        if (r["arch"] == arch and r["recipe_actual"] == rec
                and r["variant"] == variant and r["kind"] == "paired_delta"
                and r[metric] not in ("", MISSING)):
            out.append((r["provenance"], f"{float(r[metric]):+.3f}"))
    return out


