def build(rows, pooled, sha) -> str:
    t = Table(rows)
    lines = []
    section_status(lines, sha)
    section_method(lines)
    section_answers(t, lines)
    section_evidence(t, pooled, lines)
    section_artifacts(lines)
    section_provenance(lines)
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Render the TASK-07 handoff.")
    parser.add_argument("--table", default="results/tables/sink_address.csv")
    parser.add_argument("--pooled", default="results/tables/e2_pooled.csv")
    parser.add_argument("--out", default="docs/TASK_07_HANDOFF.md")
    args = parser.parse_args()

    text = build(load(Path(args.table)), load(Path(args.pooled)), git_sha())
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
